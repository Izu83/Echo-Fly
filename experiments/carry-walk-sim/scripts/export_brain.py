"""
Export the wall-dodge sub-circuit (LPLC1/2/4 -> 400 relays -> DNa01/DNa02, cut from the male CNS
connectome) into a JavaScript file the browser simulation can load straight from disk.

  input : ../wall-dodge/output/data/subnetwork.npz   (connections, signs, sides, roles)
          ../wall-dodge/output/data/layout.json      (cell-body positions, for drawing)
  output: ../web/brain_data.js                                   (sets BRAIN_DATA on window / globalThis)

The connections are stored grouped by sending neuron (CSR), so the browser only has to walk the
outgoing connections of the neurons that fired in each 1 ms step.

Run: python scripts/export_brain.py
If subnetwork.npz is missing, build it first with experiments/wall-dodge/scripts/build_subnetwork.py.
"""

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]   # the Echo-Fly folder
SRC = ROOT / "experiments" / "wall-dodge" / "output" / "data"
OUT = HERE.parent / "web" / "brain_data.js"


def main():
    npz, layout_file = SRC / "subnetwork.npz", SRC / "layout.json"
    if not npz.exists():
        sys.exit(f"missing {npz}\nrun experiments/wall-dodge/scripts/build_subnetwork.py first")
    d = np.load(npz, allow_pickle=True)
    role, side, sign, types = d["role"], d["side"], d["sign"], d["types"]
    pre, post, syn = d["pre"], d["post"], d["syn"]
    n = len(role)

    order = np.lexsort((post, pre))
    pre, post, syn = pre[order], post[order], syn[order]
    offsets = np.zeros(n + 1, dtype=int)
    np.add.at(offsets, pre + 1, 1)
    offsets = np.cumsum(offsets)

    # front view of the brain: x = fly's right, y = dorsal; falls back to a simple grid if no layout
    if layout_file.exists():
        pos = [[round(p[0], 1), round(p[1], 1)] for p in json.load(open(layout_file))["pos"]]
    else:
        pos = [[float(side[i]) * 100 + (i % 20) * 3, float(role[i]) * -60 + (i // 20) % 10 * 3] for i in range(n)]

    data = {
        "n": int(n),
        "role": role.astype(int).tolist(),
        "side": side.astype(int).tolist(),
        "sign": sign.astype(int).tolist(),
        "type": [str(t) for t in types],
        "pos": pos,
        "offsets": offsets.tolist(),
        "targets": post.astype(int).tolist(),
        "syn": syn.astype(int).tolist(),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/export_brain.py from the male CNS connectome (Janelia FlyEM, CC-BY).\n")
        f.write("(typeof window !== \"undefined\" ? window : globalThis).BRAIN_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} neurons, {len(post)} connections, {int(syn.sum())} synapses")


if __name__ == "__main__":
    main()
